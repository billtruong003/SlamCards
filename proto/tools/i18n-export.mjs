// Writes docs/localization/STRINGS.md: every player-facing string with where it shows and how
// long it may get, for translators. Source: src/locales/vi.json + src/locales/context.json.
import fs from 'node:fs';
import { fileURLToPath } from 'node:url';

const locales = new URL('../src/locales/', import.meta.url);
const out = new URL('../../docs/localization/STRINGS.md', import.meta.url);
const read = (name) => JSON.parse(fs.readFileSync(new URL(name, locales), 'utf8'));
const vi = read('vi.json');
const context = read('context.json');
const i18nSource = fs.readFileSync(new URL('../src/i18n.js', import.meta.url), 'utf8');
const langs = [...i18nSource.matchAll(/\{ code: '([^']+)', name: '([^']+)' \}/g)].map((m) => [m[1], m[2]]);
const shipped = new Set(fs.readdirSync(locales).filter((f) => f.endsWith('.json') && f !== 'context.json').map((f) => f.slice(0, -5)));

const cell = (text) => String(text ?? '').replace(/\|/g, '\\|').replace(/\n/g, '\\n');
const placeholders = [...new Set(Object.values(vi).flatMap((v) => v.match(/\{\w+\}/g) ?? []))].sort();

const groups = {};
for (const key of Object.keys(vi)) (groups[key.split('.')[0]] ??= []).push(key);

const lines = [
  '# Player-facing strings',
  '',
  'Generated by `npm run i18n:export` (proto/tools/i18n-export.mjs). Do not edit by hand:',
  'change `proto/src/locales/vi.json` (text) or `context.json` (notes), then regenerate.',
  '',
  '## How to translate',
  '',
  '- Create `proto/src/locales/<code>.json` with the same keys as `vi.json`. Missing keys fall back to English, then Vietnamese.',
  '- Keep every `{placeholder}` exactly as written; word order around it can change.',
  '- Some placeholders are filled with ready-made HTML (a coloured name, a room code); the "where" column says so.',
  '- `<b>…</b>` marks emphasis in tutorial text; keep the tags balanced. `\\n` in `menu.logo` is a line break.',
  '- "max" is roughly how many characters fit before the layout breaks.',
  '- Check a file with `npm run i18n:check <code>`; preview with `?lang=<code>` in the game URL.',
  '',
  `Placeholders in use: ${placeholders.map((p) => `\`${p}\``).join(' ')}`,
  '',
  '## Languages',
  '',
  '| Code | Name | Shipped |',
  '|---|---|---|',
  ...langs.map(([code, name]) => `| ${code} | ${name} | ${shipped.has(code) ? 'yes' : 'no'} |`),
  '',
];

for (const [group, keys] of Object.entries(groups)) {
  lines.push(`## ${group}`, '', '| Key | ID | Where | Max | Vietnamese |', '|---|---|---|---|---|');
  for (const key of keys) {
    const c = context[key] ?? {};
    lines.push(`| \`${key}\` | ${c.id ?? ''} | ${cell(c.where)} | ${c.max ?? ''} | ${cell(vi[key])} |`);
  }
  lines.push('');
}

fs.mkdirSync(new URL('.', out), { recursive: true });
fs.writeFileSync(out, lines.join('\n'));
console.log(`wrote ${fileURLToPath(out)} (${Object.keys(vi).length} keys)`);
